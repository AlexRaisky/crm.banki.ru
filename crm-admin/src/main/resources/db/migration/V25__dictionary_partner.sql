-- Справочник партнёров.
--
-- До этого список из 139 партнёров жил захардкоженным массивом PROMO_PARTNERS в
-- static/js/promo.js: он подставлялся в подсказку поля «Партнёр» на планировании промо,
-- но правился только через выкладку фронта. Переносим в БД — к уже переехавшим
-- dictionary.d_communication_name и dictionary.d_touch_point.
--
-- Состав колонок задан заказчиком: id, name, timestamp_cr, timestamp_upd.
-- UNIQUE(name) добавлен сверх этого — справочник, дубли не нужны, и он же делает
-- повторный прогон сида безопасным.
CREATE TABLE IF NOT EXISTS dictionary.d_partner (
    id            bigserial    PRIMARY KEY,
    name          varchar(200) NOT NULL,
    timestamp_cr  timestamptz  NOT NULL DEFAULT now(),
    timestamp_upd timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_d_partner_name UNIQUE (name)
);

