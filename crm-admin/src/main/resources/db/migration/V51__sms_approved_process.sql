-- Процесс «Тексты для согласования у операторов».
--
-- Пятый рядом с доставкой шаблонов, обратным ETL и двумя событийными. Заводится
-- ВКЛЮЧЁННЫМ, как и остальные: выключатель не должен менять поведение в день выката.
--
-- Что делает: находит sms-шаблоны, у которых в notice.d_com_sms_approved_template нет
-- строки или она с пустым текстом, раскладывает msg_text по правилам сотовых операторов
-- и записывает — вместе с R во всех четырёх колонках согласования.
--
-- Зачем процесс, если строка и так создаётся при доставке шаблона в прод: доставка
-- ловит только то, что заводят и правят сейчас. Сверка добирает всё остальное —
-- шаблоны, уехавшие до появления этого правила, и те, у кого доставка когда-то падала.
-- Та же логика, что у вечернего полного прохода обратного ETL.
