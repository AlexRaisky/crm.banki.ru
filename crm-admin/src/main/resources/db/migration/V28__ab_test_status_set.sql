--
-- В V27 их было два: «идёт» / «не идёт». Прежнее «не идёт» означало «не выполняется» —
-- ближайшее к нему в новом наборе «завершён». Колонка уже есть (varchar(40) DEFAULT
-- 'идёт'), default оставляем прежним: новая запись заводится как идущий тест.
--
-- На всех контурах таблица пустая — это на случай непустого test-контура.
