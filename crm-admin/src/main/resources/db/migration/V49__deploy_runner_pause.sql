-- Пауза обработчика выкатов.
--
-- Кнопка «Выкатить» ставит задание, обработчик берёт его в течение минуты. На время
-- инцидента или релизного окна это надо уметь перекрыть, не выключая таймер по ssh:
-- иначе единственный способ остановить выкаты — идти на сервер, а туда есть доступ не у
-- всех, кто видит кнопку.
--
-- Пауза останавливает ВЗЯТИЕ новых заданий, а не текущее: задание — это сборка образа и
-- пересоздание контейнера, рвать его на середине хуже, чем дать доработать.
ALTER TABLE app.deploy_runner
    ADD COLUMN IF NOT EXISTS paused     boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS paused_by  text,
    ADD COLUMN IF NOT EXISTS paused_at  timestamptz;

COMMENT ON COLUMN app.deploy_runner.paused IS 'true — обработчик не берёт новые задания; текущее доделывает';
