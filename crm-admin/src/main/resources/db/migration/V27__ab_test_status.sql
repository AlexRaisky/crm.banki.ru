-- А/Б тесты: явный статус «идёт / не идёт».
--
-- Раньше «идёт» выводилось из пустой даты окончания. Понадобился отдельный
-- проставляемый статус: тест может быть приостановлен, а дата окончания ещё
-- не наступила — по одной дате это не выразить.
ALTER TABLE app.ab_test
    ADD COLUMN IF NOT EXISTS status varchar(40) NOT NULL DEFAULT 'идёт';

-- Бэкфилл уже заведённых строк по прежнему признаку: есть дата окончания — тест
-- завершён. На проде/препроде таблица пустая, это на случай непустого test-контура.
UPDATE app.ab_test SET status = 'не идёт' WHERE date_end IS NOT NULL AND status = 'идёт';
