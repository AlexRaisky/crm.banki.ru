-- Деактивация роли вместо удаления.
--
-- Удалить роль можно было только пока ею никто не пользуется и она не встроенная —
-- то есть почти никогда. А потребность обычная: роль отжила своё, назначать её больше
-- не надо, но историю и саму запись хочется сохранить (матрица прав роли — это ответ
-- на вопрос «кто что мог год назад»).
--
-- Флаг активности. Неактивная роль остаётся в справочнике, но её носители в панель
-- не пускаются: проверка стоит там же, где проверка «учётка выключена».
ALTER TABLE app.role ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN app.role.is_active IS 'Роль активна: назначается новым учёткам, её носители могут входить';
