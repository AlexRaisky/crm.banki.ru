-- Приоритет заданий планировщика: LOW → NORMAL.
--
-- В scheduler.t_launch_settings priority — число, и его ставит не панель, а сам
-- планировщик по слову, которое мы передаём в POST /api/v1/event. Слово это одно на все
-- события и лежит в настройках интеграции; с V56 там стояло LOW, и в прод-таблице у
-- каждого заведённого события оказывалась единица.
--
-- Нужна пятёрка — это NORMAL (у Quartz пятый приоритет и есть обычный, средний).
-- Меняем и текущее значение, и умолчание: иначе на контуре, поднятом с нуля, снова
-- окажется LOW, и разница между контурами вылезет через месяц на боевом событии.
--
-- Выбор при этом остаётся за человеком: приоритет виден и меняется на экране
-- «Настройки» → «Планировщик». Здесь мы правим умолчание, а не запрещаем LOW.
UPDATE app.cron_connection SET priority = 'NORMAL' WHERE priority = 'LOW';

ALTER TABLE app.cron_connection ALTER COLUMN priority SET DEFAULT 'NORMAL';
