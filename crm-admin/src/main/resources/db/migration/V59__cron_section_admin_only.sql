-- Экран подключения к планировщику возвращается в настройки и становится
-- администраторским. Выдаваемого права под него больше нет.
--
-- V56 завела секцию set-cron, V58 переименовала её в ev-cron ради переезда в «События».
-- Обе правки оказались лишними: адрес планировщика — это одна настройка на всю панель,
-- решающая, на какой контур уедут боевые задания Quartz. Такое не выдают галкой в
-- матрице прав; на сервере ручки закрыты ролью, как у «Выкаток» и «Обработчика выкатов».
--
-- Настройка при этом действует на ВСЕХ: сами задания заводятся кнопками в карточке
-- события, и там право прежнее — ev-offline. Администратор задаёт адрес, работают с
-- заданиями все, кому разрешены события по расписанию.
--
-- Строки удаляем, а не оставляем «на всякий случай»: секция, которой нет в коде, в
-- матрице прав выглядит как забытое право и однажды будет кому-нибудь выдана.
DELETE FROM app.role_section WHERE section_id IN ('ev-cron', 'set-cron');
