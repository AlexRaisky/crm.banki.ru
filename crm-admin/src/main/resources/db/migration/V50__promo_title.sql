-- Промо: название задачи, написанное человеком.
--
-- Заголовок задачи в Jira собирался автоматически из полей строки — канал, заказчик,
-- продукт, вид рассылки, имя коммуникации, дата. Читается такой заголовок как опись
-- имущества: по нему видно параметры, но не видно, о чём задача. В самой Jira люди
-- пишут иначе — «Идут отказы по основному оферу», то есть сразу суть.
--
-- Пишет это поле маркетолог или тот, кто заводит задачу, поэтому оно живёт в плане,
-- а не подставляется правилом. Пустое — заголовок собирается автоматически, как и
-- раньше: пустая строка в плане не должна оборачиваться задачей без названия.
--
-- Не путать с communication_name и uniq_name: те технические, по ним строки
-- сопоставляются между собой и с боевой базой. Это — человеческое название, и никакой
-- машине оно не адресовано.
ALTER TABLE app.promo_plan ADD COLUMN IF NOT EXISTS title varchar(300) NOT NULL DEFAULT '';

COMMENT ON COLUMN app.promo_plan.title IS
    'Название задачи словами — заголовок задачи в Jira. Пустое: заголовок собирается автоматически';
