-- «Просмотр настроек» получает собственную секцию.
--
-- Пункт меню «Просмотр настроек» — тот же экран мастера коммуникаций, но в режиме
-- чтения. Своей секции у него не было: он повторял права секции admin (aclSection).
-- Из-за этого доступ «смотреть настройки, но не править» выдать было нельзя — а это
-- ровно тот случай, ради которого режим просмотра и делали.
--
-- Права ПЕРЕНОСИМ, а не раздаём заново: у кого был «Мастер коммуникаций», у того
-- «Просмотр настроек» и оставался виден. Без этой вставки пункт молча исчез бы у всех
-- ролей сразу после выката. Только чтение: viewer — витрина, ручки записи в
-- TemplateController по-прежнему требуют admin или templates.
INSERT INTO app.role_section (role_id, section_id, can_read, can_add, can_edit, can_delete)
SELECT rs.role_id, 'viewer', true, false, false, false
FROM app.role_section rs
WHERE rs.section_id = 'admin' AND rs.can_read
ON CONFLICT DO NOTHING;

