-- Партнёры — в общий экран справочников, значит им нужны те же две колонки, что у
-- остальных: порядок и признак активности.
--
-- Без is_active партнёра можно было только удалить. Удаление здесь ничего не чинит:
-- внешнего ключа между dictionary.d_partner и шаблонами нет, имя в template.d_template
-- останется и после удаления строки — пропадёт лишь объяснение, откуда оно взялось.
-- Выключение как раз и есть правильное действие: партнёр перестал работать с нами,
-- в новых коммуникациях его быть не должно, в старых он был.
--
-- sort_order по умолчанию одинаковый: список партнёров осмысленного порядка не имеет
-- и сортируется по алфавиту. Колонка нужна ради единообразия строки — экран настроек
-- один на все справочники и правит их одинаково.
ALTER TABLE dictionary.d_partner ADD COLUMN IF NOT EXISTS sort_order int     NOT NULL DEFAULT 100;
ALTER TABLE dictionary.d_partner ADD COLUMN IF NOT EXISTS is_active  boolean NOT NULL DEFAULT true;
