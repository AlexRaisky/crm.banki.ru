-- Процесс «Тексты смс для согласования» заводится ВЫКЛЮЧЕННЫМ.
--
-- Соседние четыре процесса включены, и это правильно: они работали и до появления
-- выключателя, а рубильник приделали потом — заведи их выключенными, и выкат тихо
-- остановил бы доставку шаблонов.
--
-- С этим наоборот. Он новый, и первое же его срабатывание пишет в боевую таблицу
-- согласований — сразу тысячами строк. Включённый по умолчанию, он сходил бы туда
-- через две минуты после старта, ещё до того, как человек успеет открыть панель:
-- решение «применять» приняли бы за него.
--
-- Поэтому после выката он стоит, в разделе видно «остановлен», и человек сначала
-- жмёт «Проверить», смотрит отчёт и только потом включает.
--
-- Отдельной миграцией, а не правкой V51: применённые миграции не переписывают —
-- у Flyway разойдётся контрольная сумма, и приложение не поднимется.
UPDATE app.sync_process
SET enabled = false, timestamp_upd = now()
WHERE code = 'sms-approved';
