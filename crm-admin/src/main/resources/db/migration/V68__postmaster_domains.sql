-- Постмастеры: несколько доменов вместо одного.
--
-- Домен был один на всю настройку, а рассылки идут с нескольких (транзакционные и
-- маркетинговые обычно разведены по поддоменам, и репутация у них разная — как раз
-- её и смотрят). Список храним строкой через запятую или перевод строки: это
-- настройка подключения, а не справочник, и заводить под неё таблицу с обвязкой
-- дороже, чем польза.
--
-- Колонку domain оставляем: она уже лежит в channel.t_postmaster_daily у каждой
-- строки метрик, и по ней раздел фильтрует. Здесь она становится «первым из
-- списка» — тем, что раздел покажет по умолчанию.
ALTER TABLE app.postmaster_connection
    ADD COLUMN IF NOT EXISTS domains text;

UPDATE app.postmaster_connection
   SET domains = coalesce(nullif(domains, ''), domain)
 WHERE id = 1;
