-- Подключение к планировщику переезжает из настроек в «События»: секция set-cron
-- становится ev-cron.
--
-- По устройству это интеграция, и стояла она среди Jira и подключений к БД правильно.
-- Но нужна она тому, кто заводит события по расписанию, и думает он в этот момент про
-- событие, а не про список интеграций, — экран там просто не нашли.
--
-- Переименовываем, а не заводим рядом: права, выданные V56, должны переехать вместе с
-- секцией. Завести новую и оставить старую значило бы получить два имени одного и того
-- же права, и однажды выдать не то.
UPDATE app.role_section SET section_id = 'ev-cron' WHERE section_id = 'set-cron';

-- Подчистить за собой: если такой строки не осталось, DELETE ничего не сделает.
DELETE FROM app.role_section WHERE section_id = 'set-cron';
