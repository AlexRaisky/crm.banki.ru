-- У импорта событий было два выключателя, и работал не тот, который видно.
--
-- В «Процессах переливов» строка event-import стояла ВКЛЮЧЁННОЙ (V39 завела все
-- процессы включёнными намеренно: выключатель не должен менять поведение в день
-- выката). А поверх неё в коде стояла проверка свойства app.event-import.enabled с
-- умолчанием false. Экран показывал «включён», импорт при этом не запускался ни разу,
-- и понять это можно было только по отсутствию строк в логе.
--
-- Свойство убрано из кода: выключатель теперь один, тот, что виден в панели.
--
-- Но включённым его не оставляем. До сих пор импорт нигде не работал, отметок «докуда
-- дочитали» нет, и первый прогон пойдёт с нуля: по 500 строк на каждую из восьми
-- таблиц каждые пять минут, пока не догонит прод. Начинать это молча, в момент выката,
-- на всех трёх контурах сразу — не то, о чём кто-то просил. Пусть человек включит сам,
-- на том контуре, где это осмысленно, и посмотрит на первый прогон.
UPDATE app.sync_process
SET enabled = false, timestamp_upd = now(),
    last_result = coalesce(last_result, 'ни разу не запускался: до V61 импорт был закрыт свойством')
WHERE code = 'event-import';
