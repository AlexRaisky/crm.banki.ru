--
-- База стала выбором из справочника (Вклады, ОСАГО, Каско, …), а всё, что уточняет
-- выборку словами — «только Москва+МО», «без тех, кто получал в июле» — раньше писали
-- в то же поле и оно переставало быть списком. Держим уточнение рядом, но отдельно:
-- по базе теперь можно сравнивать строки между собой (подсветка пересечений в один
-- день), а произвольный текст этому не мешает.
--
-- Миграция только добавляет колонку. Существующие строки получают пустое значение.

